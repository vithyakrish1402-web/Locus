// Builds src/data/floor7Aps.json: where each Floor 7 access point sits, for the test build's
// demo (it replaces the live wifi_aps table there; nothing is written to Firestore).
//
//   node scripts/build-floor7-aps.mjs [survey.csv ...]
//
// With no arguments it reads every wifi_survey_*.csv in floor7-inputs/. It keeps campus access
// points (SRMIST and SRMIST-UA, plus hidden-name radios that share their first five BSSID
// bytes with one), maps each scan's typed name to its plan spot with
// floor7-inputs/survey_name_to_plan_spot.csv, and places each radio at the spot where it was
// heard strongest (rules in scripts/lib/floor7Anchors.mjs). GPS is ignored completely.
//
// Hand fixes go in src/data/floor7ApsOverrides.json, keyed by radio (first five BSSID bytes):
//   { "48:b4:c3:6f:eb": { "place": "labC" }, "34:3a:20:8d:8a": { "x": 3, "y": -2 } }
// The output is committed, so a team member can read it and see what was placed where.
// Not part of any app build.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MIN_ANCHOR_BEST_DBM, assignSessions, buildAnchors, campusOnly, placeReadings, readMapping, readSurvey, shortScan } from './lib/floor7Anchors.mjs';

import { walkingMidpoint } from './lib/floor7DrawnPlan.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const INPUTS = join(root, 'floor7-inputs');
const OVERRIDES = join(root, 'src', 'data', 'floor7ApsOverrides.json');
const OUT = join(root, 'src', 'data', 'floor7Aps.json');

const files = process.argv.length > 2
  ? process.argv.slice(2)
  : readdirSync(INPUTS).filter((f) => /^wifi_survey_.*\.csv$/.test(f)).sort().map((f) => join(INPUTS, f));
if (files.length === 0) {
  console.error('no survey CSVs found');
  process.exit(2);
}

const planDoc = JSON.parse(readFileSync(join(INPUTS, 'floor7_plan.json'), 'utf8'));
const mapping = readMapping(readFileSync(join(INPUTS, 'survey_name_to_plan_spot.csv'), 'utf8'));
const overrides = existsSync(OVERRIDES) ? JSON.parse(readFileSync(OVERRIDES, 'utf8')) : {};

const raw = assignSessions(files.flatMap((f) => readSurvey(readFileSync(f, 'utf8'), basename(f))));
const { placed, dropped, held } = placeReadings(raw, mapping);
const campus = campusOnly(placed);
// Positions in the file are plan metres as drawn, so the walk is measured at scale 1.
const midpoint = walkingMidpoint(planDoc);
const radios = buildAnchors(campus, { overrides, planDoc, mapping, midpoint });

const doc = {
  kind: 'floor7-aps-v2',
  note: 'Generated by scripts/build-floor7-aps.mjs from floor7-inputs/. Positions are plan metres BEFORE PLAN_SCALE (src/utils/floor7Plan.js). Do not edit by hand: put fixes in floor7ApsOverrides.json.',
  scans: { used: new Set(placed.map((r) => r.scan)).size, dropped: dropped.map(shortScan), held: held.map(shortScan) },
  overrides,
  radios: radios.map((r) => ({ ...r, heard: r.heard.slice(0, 6) })),
};
writeFileSync(OUT, `${JSON.stringify(doc, null, 1)}\n`);

const leftOut = buildAnchors(campus, { overrides, planDoc, mapping, midpoint, minBestDbm: -Infinity }).length - radios.length;
const count = (pred) => radios.filter(pred).length;
console.log(`${raw.length} readings in ${files.length} files, ${placed.length} placed, ${campus.length} campus, ${radios.length} radios, ${radios.reduce((n, r) => n + r.bssids.length, 0)} BSSIDs`);
console.log(`scans used: ${doc.scans.used}; dropped: ${doc.scans.dropped.join(', ') || 'none'}; held back: ${doc.scans.held.join(', ') || 'none'}`);
console.log(`placed: ${count((r) => r.basis === 'best')} at their best spot, ${count((r) => r.basis === 'tie')} between two spots, ${count((r) => r.basis === 'override')} by hand`);
console.log(`radios left out for never being heard stronger than ${MIN_ANCHOR_BEST_DBM} dBm: ${leftOut}`);
console.log(`${count((r) => r.single_spot)} heard at one spot only; ${count((r) => r.guess.length > 0)} rest on a guessed spot`);
