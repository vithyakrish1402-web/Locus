// Builds src/data/floor7Aps.json: where each Floor 7 access point sits, for the test build's
// demo (it replaces the live wifi_aps table there; nothing is written to Firestore).
//
//   node scripts/build-floor7-aps.mjs <survey.csv> [more.csv ...]
//
// Reads the raw survey exports, keeps campus access points (SSID allowlist, plus hidden-name
// radios that share their first five BSSID bytes with one), and places each radio at the
// hand-placed spot where it was heard strongest. Hand fixes go in src/data/floor7ApsOverrides.json
// (keyed by radio, e.g. "48:b4:c3:6f:eb": { "spot": "TP706" } or { "x": 3, "y": -2 }); the output
// is committed, so a team member can read it and see what was placed where.
//
// Placement rules are in scripts/lib/floor7Anchors.mjs. Not part of any app build.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { anchorRadios, campusOnly, readSurvey } from './lib/floor7Anchors.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const MAP = join(root, 'src', 'data', 'floor7Map.json');
const OVERRIDES = join(root, 'src', 'data', 'floor7ApsOverrides.json');
const OUT = join(root, 'src', 'data', 'floor7Aps.json');

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('usage: node scripts/build-floor7-aps.mjs <survey.csv> [more.csv ...]');
  process.exit(2);
}

const map = JSON.parse(readFileSync(MAP, 'utf8'));
const overrides = existsSync(OVERRIDES) ? JSON.parse(readFileSync(OVERRIDES, 'utf8')) : {};
const raw = files.flatMap((f) => readSurvey(readFileSync(f, 'utf8'), basename(f)));
const campus = campusOnly(raw);
const radios = anchorRadios(campus, map.spots, { overrides });

const doc = {
  kind: 'floor7-aps-v1',
  placeholderMap: map.placeholder === true,
  note: 'Generated by scripts/build-floor7-aps.mjs. Positions are metres in the Floor 7 frame, taken from floor7Map.json spots. Do not edit by hand: put fixes in floor7ApsOverrides.json.',
  radios,
};
writeFileSync(OUT, `${JSON.stringify(doc, null, 1)}\n`);

const basis = (b) => radios.filter((r) => r.basis === b).length;
console.log(`${raw.length} readings, ${campus.length} campus, ${radios.length} radios, ${radios.reduce((n, r) => n + r.bssids.length, 0)} BSSIDs`);
console.log(`placed: ${basis('best')} at their best spot, ${basis('tie')} between two spots, ${basis('single-spot')} heard at one spot only, ${basis('override')} by hand`);
if (map.placeholder) console.log('NOTE: floor7Map.json is still placeholder geometry, so these positions are too.');
